// shop_constants.js — 商店 / 卡池 / 升級經濟
//
// **全部照抄 TFT（Teamfight Tactics）現行數值，一個都沒改。**
// 理由：這一層的參數彼此高度耦合（卡池深度 × 商店機率 × 升級曲線 ×
// 合成張數共同決定「多久能三星」），隨手改一個就會壞掉整局節奏。
// TFT 是被幾千萬局實測過的一組自洽解，先當地基用，等有完整一局的
// 模擬（bot 對局 + 勝率分布）之後再逐項替換。
//
// 跟數值層（constants.js）不同，這裡的數字**沒有任何實證來源**——
// 不要拿它們去校準任何東西，它們只是暫借的鷹架。

// --- 費用與卡池 ---------------------------------------------------------
// POOL_COPIES：每一張「不同的卡」在共享卡池裡有幾份。
// 這是自走棋的核心稀缺機制——八個玩家共用同一個池，別人拿走的你就抽不到。
export const POOL_COPIES = { 1: 30, 2: 25, 3: 18, 4: 10, 5: 9 };

// POOL_UNITS：每個費用有幾張不同的卡（TFT 現行配置）。
// 我們現在只有 25 張卡（7/6/6/4/2，見 docs/卡牌設計.md §2），
// 離這個規模還很遠。卡池深度要照「實際張數」算，這裡是目標值。
export const POOL_UNITS = { 1: 13, 2: 13, 3: 13, 4: 12, 5: 8 };

/** 各費用的總卡數 = 張數 × 每張份數。 */
export const POOL_TOTAL = Object.fromEntries(
  [1, 2, 3, 4, 5].map((c) => [c, POOL_UNITS[c] * POOL_COPIES[c]]),
);  // { 1: 390, 2: 325, 3: 234, 4: 120, 5: 72 }

// --- 商店 ---------------------------------------------------------------
export const SHOP_SIZE = 5;
export const REROLL_COST = 2;

/**
 * 商店機率（依等級）。索引 = 玩家等級，值 = [1費, 2費, 3費, 4費, 5費]。
 * 每一列相加為 1。等級 1 與 2 都是純 1 費。
 */
export const ROLL_ODDS = {
  1:  [1.00, 0.00, 0.00, 0.00, 0.00],
  2:  [1.00, 0.00, 0.00, 0.00, 0.00],
  3:  [0.75, 0.25, 0.00, 0.00, 0.00],
  4:  [0.55, 0.30, 0.15, 0.00, 0.00],
  5:  [0.45, 0.33, 0.20, 0.02, 0.00],
  6:  [0.30, 0.40, 0.25, 0.05, 0.00],
  7:  [0.16, 0.30, 0.43, 0.10, 0.01],
  8:  [0.15, 0.20, 0.32, 0.30, 0.03],
  9:  [0.10, 0.17, 0.25, 0.33, 0.15],
  10: [0.05, 0.10, 0.20, 0.40, 0.25],
};

export const MAX_LEVEL = 10;

// --- 升級 ---------------------------------------------------------------
/**
 * 升到該等級所需的 XP（不是累計）。索引 = 目標等級。
 * 注意 9 -> 10 跟 8 -> 9 一樣是 68，不是繼續往上長——TFT 在這裡刻意壓平，
 * 讓「衝十等」在後期是可行的，而不是只有一條路。
 */
export const LEVEL_XP = { 2: 2, 3: 2, 4: 6, 5: 10, 6: 20, 7: 36, 8: 60, 9: 68, 10: 68 };

/** 累計 XP（從 1 等算起），做進度條與「還差幾回合」用。 */
export const LEVEL_XP_CUMULATIVE = (() => {
  const out = { 1: 0 };
  let acc = 0;
  for (let lv = 2; lv <= MAX_LEVEL; lv++) { acc += LEVEL_XP[lv]; out[lv] = acc; }
  return out;
})();  // { 1:0, 2:2, 3:4, 4:10, 5:20, 6:40, 7:76, 8:136, 9:204, 10:272 }

/** 買經驗：4 金換 4 XP。每回合另外自動獲得 2 XP。 */
export const XP_PURCHASE = { gold: 4, xp: 4 };
export const XP_PER_ROUND = 2;

// --- 合成 ---------------------------------------------------------------
/** 三張合二星、三張二星合三星（= 9 張一星）。 */
export const COPIES_PER_STAR = 3;
export const COPIES_TO_STAR = { 1: 1, 2: 3, 3: 9 };
export const MAX_STAR = 3;

/**
 * 抽到某費用之後，抽到「特定一張卡」的條件機率。
 * = 該卡剩餘份數 / 該費用池中剩餘總份數。這裡給的是滿池基準值。
 */
export function baseCardOdds(cost) {
  return POOL_COPIES[cost] / POOL_TOTAL[cost];
}

/** 等級 lv 的商店單格抽到某費用卡的機率。 */
export function rollOdds(lv, cost) {
  const row = ROLL_ODDS[Math.max(1, Math.min(MAX_LEVEL, lv))];
  return row[cost - 1];
}
