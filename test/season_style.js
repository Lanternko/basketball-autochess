import assert from 'node:assert/strict';
import fs from 'node:fs';
import {withSeasonStyle} from '../src/season_style.js';
import {TEAMS,BASELINE} from '../src/teams.js';
import * as M from '../src/probability_model.js';
import {simulateGame,teamRebound} from '../src/simulation_engine.js';
const ref=JSON.parse(fs.readFileSync(new URL('../data/reference-seasons.json',import.meta.url)));
const team=withSeasonStyle(TEAMS.LAL,ref.teams.LAL,{freeThrowStyle:true});
assert.equal(TEAMS.LAL.roster[0].shotProfile,undefined);
const base=BASELINE.roster,handler={...team.roster[0],shotProfile:{threeRate:0,freeThrowsPerAttempt:.4}};
const ctx=M.teammateContext(base,0);
const p=M.possessionProbabilities(handler,ctx,base[0],M.helpDefense(base),teamRebound(base),teamRebound(base),70);
assert.equal(p.zone.long,0);
assert.ok(Math.abs(p.TOV-p.pTovTouch)<1e-12);
assert.ok(Math.abs(2*p.pFoul/(1-p.pTovTouch-p.pFoul)-.4)<1e-12);
assert.ok(Math.abs(Object.values(p.zone).reduce((a,b)=>a+b,0)-1)<1e-12);
const noStyle=M.possessionProbabilities({...handler,shotProfile:undefined},ctx,base[0],M.helpDefense(base),70,70,70);
assert.equal(p.ftPct,noStyle.ftPct);
const r=simulateGame({...team,roster:team.roster.map(x=>({...x,shotProfile:{...x.shotProfile,threeRate:0}}))},BASELINE,{possessions:100,fatigue:false,contextScale:.5,turnoverScale:1.8});
assert.equal(r.statA.fg3a,0);
assert.throws(()=>simulateGame(team,BASELINE,{contextScale:NaN}));
console.log('PASS tendency isolation, nonshooters, consistent turnover EV, FT event ratio, unchanged FT accuracy, engine flow');
