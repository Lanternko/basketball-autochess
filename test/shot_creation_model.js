import assert from 'node:assert/strict';
import {creationHandlerWeights,creationShootProbability,creationReceiverWeights} from '../src/shot_creation_model.js';
import {onCourtCollector} from '../reports/player-impact-v1/on-court.mjs';
const card=(self,ast,caught)=>({shotCreationMeasurement:{selfMakesPerMinute:self,assistsPerMinute:ast,assistedMakesPerMinute:caught}});
const creator=card(.2,.3,.1),finisher=card(.05,.02,.25);
assert.deepEqual(creationHandlerWeights([creator,finisher]),[.5,.07]);
assert.equal(creationShootProbability(creator,5,5),.4);
assert.equal(creationShootProbability(creator,4,5),1);
assert.deepEqual(creationReceiverWeights([creator,finisher],0,[.4,.5]),[0,.5]);
assert.throws(()=>creationHandlerWeights([{}]));
assert.throws(()=>creationReceiverWeights([creator,finisher],0,[.5]));
const c=onCourtCollector(),active=[1,2,3,4,5,6],teamA={teamId:1,lineup:[1,2,3,4,5],active},teamB={teamId:2,lineup:[11,12,13,14,15],active:[11,12,13,14,15]};
c.event({type:'FGM',side:0,zone:'long',playerId:1,teams:[teamA,teamB]});
c.event({type:'FGX',side:1,zone:'short',playerId:11,teams:[{...teamA,lineup:[2,3,4,5,6]},teamB]});
c.event({type:'GAME_END',teams:[teamA,teamB]});
const r=c.finish(),p=id=>r.players.find(p=>p.playerId===id);
assert.equal(r.games,1);assert.equal(p(1).on.fgm,1);assert.equal(p(1).own.fg3m,1);assert.equal(p(1).teammates.fga,0);
assert.equal(p(1).off.opp_fga,1);assert.equal(p(6).off.fg3m,1);assert.equal(p(6).on.opp_fga,1);
assert.equal(r.players.reduce((s,p)=>s+p.on.fga,0),10);assert.equal(r.players.reduce((s,p)=>s+p.teammates.fga,0),8);
console.log('shot creation and on-court accounting: production priors, receiver conditioning, invalid input, substitutions, own-shot exclusion and five-player conservation passed');
